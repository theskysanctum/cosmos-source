#!/usr/bin/env python3
"""GameBox Add-on Studio - a form-driven scaffolding tool for
media/addon_backend.py's own add-on format (Music/Photos content
sources - see that module's own docstring for the full contract this
generates against). No hand-written Python required for the common
case: pick a type, name a few categories/albums, list title+path pairs
under each, export - it writes a real addon.json + a small, static,
data-only addon.py that just returns exactly what you typed.

Deliberately data-only, not a live scraper/API-client generator - a
real dynamic add-on (hitting a webdav/API backend) still needs someone
to hand-write that addon.py, same as today; this tool covers "I have a
fixed, curated list of things to add" cleanly and safely, which is the
common case for a personal/household console.

Generated addon.py modules carry a real `STUDIO_DATA` module-level dict
(the exact structure this tool wrote) purely so "Load for Editing" can
read it straight back via introspection - the same trick astronar_
studio.py's own bodypart.py generator uses (POS/HPR/JOINT constants) -
rather than trying to parse arbitrary Python back into form fields."""
import shutil
import sys
from pathlib import Path

import gi

gi.require_version("Gtk", "3.0")
from gi.repository import Gtk  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parent))
import repo_paths  # noqa: E402


def _slugify(name):
	out = []
	for ch in name.strip().lower():
		if ch.isalnum():
			out.append(ch)
		elif out and out[-1] != "_":
			out.append("_")
	return "".join(out).strip("_") or "addon"


def render_addon_py(media_type, categories):
	"""`categories` is [{"id", "name", "items": [{"id","title","path"}, ...]}, ...].
	Music add-ons expose list_categories()/list_items(); Photos expose
	list_albums()/list_photos() - both read from the exact same
	STUDIO_DATA structure, just under the names media/addon_backend.py's
	own load_addon() actually looks for per type (see its own
	docstring)."""
	list_fn = "list_categories" if media_type == "music" else "list_albums"
	items_fn = "list_items" if media_type == "music" else "list_photos"
	return f'''"""Generated by GameBox Add-on Studio - a static, data-only
add-on. Re-export from Add-on Studio to change its content instead of
hand-editing STUDIO_DATA below (it's read back by "Load for Editing")."""

STUDIO_DATA = {categories!r}


def {list_fn}():
	return [{{"id": c["id"], "name": c["name"]}} for c in STUDIO_DATA]


def {items_fn}(category_id):
	for c in STUDIO_DATA:
		if c["id"] == category_id:
			return [dict(item) for item in c["items"]]
	return []
'''


class AddonStudio(Gtk.Window):
	def __init__(self, gamebox_dir):
		super().__init__(title="GameBox Add-on Studio")
		self.set_default_size(900, 620)
		self.connect("destroy", Gtk.main_quit)
		self.gamebox_dir = gamebox_dir
		self.addons_root = gamebox_dir / "media" / "addons"
		self.categories = []
		self.current_category = -1

		root_box = Gtk.Box(orientation=Gtk.Orientation.HORIZONTAL, spacing=12, margin=10)
		self.add(root_box)

		left = Gtk.Box(orientation=Gtk.Orientation.VERTICAL, spacing=8)
		left.set_size_request(320, -1)
		root_box.pack_start(left, False, False, 0)

		left.pack_start(Gtk.Label(label="<b>Manage installed add-ons</b>", use_markup=True, xalign=0), False, False, 0)
		manage_scroller = Gtk.ScrolledWindow()
		manage_scroller.set_size_request(-1, 200)
		left.pack_start(manage_scroller, False, False, 0)
		self.manage_listbox = Gtk.ListBox()
		manage_scroller.add(self.manage_listbox)
		self._refresh_manage_list()

		left.pack_start(Gtk.Separator(), False, False, 0)
		left.pack_start(Gtk.Label(label="<b>New add-on</b>", use_markup=True, xalign=0), False, False, 0)

		form = Gtk.Grid(row_spacing=6, column_spacing=6)
		left.pack_start(form, False, False, 0)
		row = 0
		form.attach(Gtk.Label(label="Type:", xalign=0), 0, row, 1, 1)
		self.type_combo = Gtk.ComboBoxText()
		self.type_combo.append_text("music")
		self.type_combo.append_text("photos")
		self.type_combo.set_active(0)
		form.attach(self.type_combo, 1, row, 1, 1)
		row += 1
		form.attach(Gtk.Label(label="Name:", xalign=0), 0, row, 1, 1)
		self.name_entry = Gtk.Entry()
		self.name_entry.connect("changed", self._on_name_changed)
		form.attach(self.name_entry, 1, row, 1, 1)
		row += 1
		self.id_label = Gtk.Label(label="id: (type a name above)", xalign=0)
		form.attach(self.id_label, 0, row, 2, 1)
		row += 1
		form.attach(Gtk.Label(label="Description:", xalign=0), 0, row, 1, 1)
		self.desc_entry = Gtk.Entry()
		form.attach(self.desc_entry, 1, row, 1, 1)

		cat_box = Gtk.Box(orientation=Gtk.Orientation.HORIZONTAL, spacing=4)
		self.cat_label = Gtk.Label(label="No categories yet")
		cat_box.pack_start(self.cat_label, True, True, 0)
		for label, handler in (("<", self._on_cat_prev), (">", self._on_cat_next), ("Add", self._on_cat_add), ("Remove", self._on_cat_remove)):
			btn = Gtk.Button(label=label)
			btn.connect("clicked", handler)
			cat_box.pack_start(btn, False, False, 0)
		left.pack_start(cat_box, False, False, 0)

		cat_name_box = Gtk.Box(orientation=Gtk.Orientation.HORIZONTAL, spacing=4)
		cat_name_box.pack_start(Gtk.Label(label="Category name:"), False, False, 0)
		self.cat_name_entry = Gtk.Entry()
		self.cat_name_entry.connect("changed", self._on_cat_name_changed)
		cat_name_box.pack_start(self.cat_name_entry, True, True, 0)
		left.pack_start(cat_name_box, False, False, 0)

		export_btn = Gtk.Button(label="Export Add-on")
		export_btn.connect("clicked", self._on_export)
		left.pack_start(export_btn, False, False, 0)

		self.status_label = Gtk.Label(label="", xalign=0)
		self.status_label.set_line_wrap(True)
		left.pack_start(self.status_label, False, False, 0)

		right = Gtk.Box(orientation=Gtk.Orientation.VERTICAL, spacing=8)
		root_box.pack_start(right, True, True, 0)
		right.pack_start(Gtk.Label(label="<b>Items in the current category</b>", use_markup=True, xalign=0), False, False, 0)

		item_scroller = Gtk.ScrolledWindow()
		right.pack_start(item_scroller, True, True, 0)
		self.items_listbox = Gtk.ListBox()
		item_scroller.add(self.items_listbox)

		add_item_box = Gtk.Box(orientation=Gtk.Orientation.HORIZONTAL, spacing=4)
		self.item_title_entry = Gtk.Entry()
		self.item_title_entry.set_placeholder_text("Title")
		add_item_box.pack_start(self.item_title_entry, True, True, 0)
		self.item_path_entry = Gtk.Entry()
		self.item_path_entry.set_placeholder_text("Path or URL")
		add_item_box.pack_start(self.item_path_entry, True, True, 0)
		add_item_btn = Gtk.Button(label="Add Item")
		add_item_btn.connect("clicked", self._on_item_add)
		add_item_box.pack_start(add_item_btn, False, False, 0)
		right.pack_start(add_item_box, False, False, 0)

		self.show_all()

	def _on_name_changed(self, _entry):
		name = self.name_entry.get_text()
		self.id_label.set_text(f"id: {_slugify(name)}" if name.strip() else "id: (type a name above)")

	def _update_cat_label(self):
		if not self.categories:
			self.cat_label.set_text("No categories yet")
		else:
			self.cat_label.set_text(f"Category {self.current_category + 1} of {len(self.categories)}")

	def _refresh_cat_name_entry(self):
		self.cat_name_entry.handler_block_by_func(self._on_cat_name_changed)
		self.cat_name_entry.set_text(self.categories[self.current_category]["name"] if self.categories else "")
		self.cat_name_entry.handler_unblock_by_func(self._on_cat_name_changed)

	def _refresh_items_list(self):
		for child in list(self.items_listbox.get_children()):
			self.items_listbox.remove(child)
		if not self.categories:
			self.items_listbox.show_all()
			return
		items = self.categories[self.current_category]["items"]
		for i, item in enumerate(items):
			row = Gtk.ListBoxRow()
			box = Gtk.Box(orientation=Gtk.Orientation.HORIZONTAL, spacing=8, margin=4)
			row.add(box)
			box.pack_start(Gtk.Label(label=f"{item['title']}  ({item['path']})", xalign=0), True, True, 0)
			remove_btn = Gtk.Button(label="Remove")
			remove_btn.connect("clicked", self._on_item_remove, i)
			box.pack_start(remove_btn, False, False, 0)
			self.items_listbox.add(row)
		self.items_listbox.show_all()

	def _on_cat_add(self, _button):
		self.categories.append({"id": _slugify(f"cat{len(self.categories)}"), "name": f"Category {len(self.categories) + 1}", "items": []})
		self.current_category = len(self.categories) - 1
		self._update_cat_label()
		self._refresh_cat_name_entry()
		self._refresh_items_list()

	def _on_cat_remove(self, _button):
		if not self.categories:
			return
		del self.categories[self.current_category]
		self.current_category = min(self.current_category, len(self.categories) - 1)
		self._update_cat_label()
		self._refresh_cat_name_entry()
		self._refresh_items_list()

	def _on_cat_prev(self, _button):
		if self.categories:
			self.current_category = (self.current_category - 1) % len(self.categories)
			self._update_cat_label()
			self._refresh_cat_name_entry()
			self._refresh_items_list()

	def _on_cat_next(self, _button):
		if self.categories:
			self.current_category = (self.current_category + 1) % len(self.categories)
			self._update_cat_label()
			self._refresh_cat_name_entry()
			self._refresh_items_list()

	def _on_cat_name_changed(self, _entry):
		if self.categories:
			name = self.cat_name_entry.get_text()
			self.categories[self.current_category]["name"] = name
			self.categories[self.current_category]["id"] = _slugify(name)
			self._update_cat_label()

	def _on_item_add(self, _button):
		if not self.categories:
			self.status_label.set_text("Add a category first.")
			return
		title = self.item_title_entry.get_text().strip()
		path = self.item_path_entry.get_text().strip()
		if not title or not path:
			self.status_label.set_text("Give the item both a title and a path/URL.")
			return
		items = self.categories[self.current_category]["items"]
		items.append({"id": path, "title": title, "path": path})
		self.item_title_entry.set_text("")
		self.item_path_entry.set_text("")
		self._refresh_items_list()

	def _on_item_remove(self, _button, index):
		del self.categories[self.current_category]["items"][index]
		self._refresh_items_list()

	def _refresh_manage_list(self):
		for child in list(self.manage_listbox.get_children()):
			self.manage_listbox.remove(child)
		for media_type in ("music", "photos"):
			type_dir = self.addons_root / media_type
			if not type_dir.is_dir():
				continue
			for addon_dir in sorted(type_dir.iterdir()):
				if not addon_dir.is_dir() or addon_dir.name == "local_files":
					continue
				manifest_path = addon_dir / "addon.json"
				name = addon_dir.name
				if manifest_path.is_file():
					import json
					try:
						name = json.loads(manifest_path.read_text()).get("name", name)
					except (OSError, ValueError):
						pass
				self.manage_listbox.add(self._make_manage_row(media_type, addon_dir.name, name))
		self.manage_listbox.show_all()

	def _make_manage_row(self, media_type, addon_id, name):
		row = Gtk.ListBoxRow()
		box = Gtk.Box(orientation=Gtk.Orientation.HORIZONTAL, spacing=6, margin=4)
		row.add(box)
		box.pack_start(Gtk.Label(label=f"[{media_type}] {name}", xalign=0), True, True, 0)
		edit_btn = Gtk.Button(label="Edit")
		edit_btn.connect("clicked", self._on_load_for_editing, media_type, addon_id)
		box.pack_start(edit_btn, False, False, 0)
		delete_btn = Gtk.Button(label="Delete")
		delete_btn.connect("clicked", self._on_delete, media_type, addon_id)
		box.pack_start(delete_btn, False, False, 0)
		return row

	def _on_delete(self, _button, media_type, addon_id):
		shutil.rmtree(self.addons_root / media_type / addon_id, ignore_errors=True)
		self._refresh_manage_list()
		self.status_label.set_text(f"Deleted {media_type}/{addon_id}.")

	def _on_load_for_editing(self, _button, media_type, addon_id):
		addon_dir = self.addons_root / media_type / addon_id
		addon_py = addon_dir / "addon.py"
		if not addon_py.is_file():
			self.status_label.set_text(f"'{addon_id}' has no addon.py.")
			return
		import importlib.util
		spec = importlib.util.spec_from_file_location(f"addon_studio_edit_{addon_id}", addon_py)
		module = importlib.util.module_from_spec(spec)
		try:
			spec.loader.exec_module(module)
		except Exception as exc:
			self.status_label.set_text(f"Couldn't load '{addon_id}': {exc}")
			return
		data = getattr(module, "STUDIO_DATA", None)
		if data is None:
			self.status_label.set_text(f"'{addon_id}' isn't editable here - no STUDIO_DATA (likely hand-coded).")
			return
		self.categories = [dict(c) for c in data]
		self.current_category = 0 if self.categories else -1
		self.type_combo.set_active(0 if media_type == "music" else 1)
		manifest_path = addon_dir / "addon.json"
		import json
		try:
			manifest = json.loads(manifest_path.read_text())
			self.name_entry.set_text(manifest.get("name", addon_id))
			self.desc_entry.set_text(manifest.get("description", ""))
		except (OSError, ValueError):
			pass
		self._update_cat_label()
		self._refresh_cat_name_entry()
		self._refresh_items_list()
		self.status_label.set_text(f"Loaded '{addon_id}' - re-export will need a different name (or delete this one first to reuse it).")

	def _on_export(self, _button):
		name = self.name_entry.get_text().strip()
		if not name:
			self.status_label.set_text("Give the add-on a name first.")
			return
		if not self.categories:
			self.status_label.set_text("Add at least one category first.")
			return
		media_type = self.type_combo.get_active_text()
		addon_id = _slugify(name)
		out_dir = self.addons_root / media_type / addon_id
		if out_dir.exists():
			self.status_label.set_text(f"An add-on called '{addon_id}' already exists at {out_dir} - pick a different name.")
			return
		try:
			out_dir.mkdir(parents=True, exist_ok=False)
			manifest = {"name": name, "description": self.desc_entry.get_text().strip()}
			import json
			(out_dir / "addon.json").write_text(json.dumps(manifest, indent=4))
			(out_dir / "addon.py").write_text(render_addon_py(media_type, self.categories))
			self.status_label.set_text(f"Exported to {out_dir} - it'll show up in {media_type}'s Add-ons list next time GameBox opens.")
			self._refresh_manage_list()
		except Exception as exc:
			shutil.rmtree(out_dir, ignore_errors=True)
			self.status_label.set_text(f"Export failed: {exc}")


if __name__ == "__main__":
	try:
		gamebox_dir = repo_paths.require_dir(repo_paths.gamebox_dir(), "GameBox")
	except FileNotFoundError as exc:
		dialog = Gtk.MessageDialog(message_type=Gtk.MessageType.ERROR, buttons=Gtk.ButtonsType.OK, text=str(exc))
		dialog.run()
		sys.exit(1)
	AddonStudio(gamebox_dir)
	Gtk.main()
